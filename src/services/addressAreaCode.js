// TourAPI 원본 데이터에 실제 존재하지 않는 지역명("전남광주통합특별시")이 섞여 있는 레코드들이
// 있다. 실제 시/군/구를 보면 전남과 광주가 뒤섞여 있어(예: 강진군/여수시는 전남, 남구/칠석동은
// 광주) 어느 한쪽으로 단정할 수 없으므로, 접두어 매칭 전에 걸러내고 진짜 미분류로 남긴다.
const KNOWN_BAD_PREFIXES = ['전남광주통합특별시'];

function inferAreaCodeFromAddress(addr1) {
  if (!addr1) return null;
  const trimmed = addr1.trim();
  if (KNOWN_BAD_PREFIXES.some((bad) => trimmed.startsWith(bad))) return null;
  const match = AREA_PREFIXES.find(([prefix]) => trimmed.startsWith(prefix));
  return match ? match[1] : null;
}

module.exports = { inferAreaCodeFromAddress };
